"""Render any stored Report to PDF, DOCX, XLSX or CSV.

Every export carries: authoring date, status and review state, sources used, assumptions,
missing evidence, approval history and the assistance-only disclaimer.
"""
from __future__ import annotations

import csv
import io
import json
import os
import re
from typing import Any

from ..models import Report

DISCLAIMER = ("Generated by the DG Compliance & Emergency Response Assistant. This document is decision support only. "
              "It is NOT a certification, legal compliance confirmation or regulatory approval. Conclusions must be "
              "reviewed and authorised by qualified personnel against the applicable authoritative regulations.")

_SKIP_KEYS = {"evidence", "coverage", "categories", "matrix_config"}


def _title(k: str) -> str:
    return k.replace("_", " ").strip().capitalize()


def _collect(content: dict, key_names: tuple[str, ...]) -> list:
    """Find values for given keys anywhere in the content tree."""
    found = []

    def walk(o):
        if isinstance(o, dict):
            for k, v in o.items():
                if k in key_names and v:
                    found.extend(v if isinstance(v, list) else [v])
                else:
                    walk(v)
        elif isinstance(o, list):
            for i in o:
                walk(i)
    walk(content)
    return found


def header_info(report: Report) -> dict:
    c = report.content or {}
    sources = []
    for ev in _collect(c, ("evidence",)) + ([c["rule_table"]["source"]] if isinstance(c.get("rule_table"), dict) else []):
        if isinstance(ev, dict) and ev.get("source_code"):
            s = f"{ev.get('title')} — {ev.get('edition')} {ev.get('amendment') or ''} [{ev.get('source_code')}; " \
                f"{ev.get('source_verification_status')}; {ev.get('section_ref') or 'no section ref'}]"
            if s not in sources:
                sources.append(s)
    return {
        "Title": report.title, "Report ID": report.id, "Type": report.kind,
        "Authoring date (UTC)": report.created_at.strftime("%Y-%m-%d %H:%M"),
        "Review status": report.status.upper(),
        "Approval requirement": "Authorised DGSA approver required" if report.criticality == "critical"
        else "Reviewer sign-off required",
        "Sources": sources or ["No authoritative regulatory source used"],
        "Assumptions": _collect(c, ("assumptions",)) or ["None recorded"],
        "Missing evidence": _collect(c, ("missing_information", "required_inputs_missing", "not_covered")) or ["None recorded"],
        "Approval history": [f"{a.created_at:%Y-%m-%d %H:%M} — {a.decision.upper()} by user #{a.user_id}"
                             f"{' (' + a.qualification + ')' if a.qualification else ''}: {a.comment}"
                             for a in report.approvals] or ["No review recorded"],
    }


def _flatten(obj: Any, prefix: str = "") -> list[tuple[str, str]]:
    rows = []
    if isinstance(obj, dict):
        for k, v in obj.items():
            if k in _SKIP_KEYS:
                continue
            rows += _flatten(v, f"{prefix}.{k}" if prefix else k)
    elif isinstance(obj, list):
        if all(not isinstance(i, (dict, list)) for i in obj):
            rows.append((prefix, "; ".join(str(i) for i in obj)))
        else:
            for i, v in enumerate(obj):
                rows += _flatten(v, f"{prefix}[{i + 1}]")
    else:
        rows.append((prefix, "" if obj is None else str(obj)))
    return rows


def to_csv(report: Report) -> bytes:
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(["field", "value"])
    for k, v in header_info(report).items():
        w.writerow([k, "; ".join(map(str, v)) if isinstance(v, list) else v])
    for k, v in _flatten(report.content):
        w.writerow([k, v])
    w.writerow(["disclaimer", DISCLAIMER])
    return buf.getvalue().encode("utf-8-sig")


def to_xlsx(report: Report) -> bytes:
    from openpyxl import Workbook
    from openpyxl.styles import Font, PatternFill

    wb = Workbook()
    ws = wb.active
    ws.title = "Summary"
    ws.append(["Field", "Value"])
    for k, v in header_info(report).items():
        ws.append([k, "\n".join(map(str, v)) if isinstance(v, list) else str(v)])
    ws.append(["Disclaimer", DISCLAIMER])
    for c in ws[1]:
        c.font = Font(bold=True)
    ws.column_dimensions["A"].width, ws.column_dimensions["B"].width = 28, 120
    det = wb.create_sheet("Detail")
    det.append(["Field", "Value"])
    for row in _flatten(report.content):
        det.append(list(row))
    det.column_dimensions["A"].width, det.column_dimensions["B"].width = 60, 120
    c = report.content or {}
    pairs = c.get("pairs")
    if isinstance(pairs, list) and pairs:
        ps = wb.create_sheet("Pairs")
        cols = ["a", "b", "status", "code", "label", "issues", "conditions", "result", "flags"]
        ps.append(cols)
        fills = {"conflict": "FFC7CE", "hold": "D9D9D9", "requirement": "FFEB9C"}
        for p in pairs:
            ps.append(["; ".join(map(str, p.get(k))) if isinstance(p.get(k), list) else str(p.get(k, "") or "")
                       for k in cols])
            color = fills.get(p.get("status"))
            if color:
                for cell in ps[ps.max_row]:
                    cell.fill = PatternFill("solid", fgColor=color)
    out = io.BytesIO()
    wb.save(out)
    return out.getvalue()


def _sections(report: Report) -> list[tuple[str, Any]]:
    c = report.content or {}
    if isinstance(c.get("sections"), list):  # ERP style
        return [(f"{s['number']}. {s['title']}", s["content"]) for s in c["sections"]]
    return [(_title(k), v) for k, v in c.items() if k not in _SKIP_KEYS]


def to_docx(report: Report) -> bytes:
    from docx import Document
    from docx.shared import Pt

    doc = Document()
    doc.add_heading(report.title, 0)
    p = doc.add_paragraph(DISCLAIMER)
    p.runs[0].font.size = Pt(8)
    t = doc.add_table(rows=0, cols=2)
    t.style = "Light Grid Accent 1"
    for k, v in header_info(report).items():
        r = t.add_row().cells
        r[0].text = k
        r[1].text = "\n".join(map(str, v)) if isinstance(v, list) else str(v)

    def emit(v, level=0):
        if isinstance(v, dict):
            for k, vv in v.items():
                if k in _SKIP_KEYS:
                    continue
                if isinstance(vv, (dict, list)):
                    doc.add_paragraph(_title(k)).runs[0].bold = True
                    emit(vv, level + 1)
                else:
                    doc.add_paragraph(f"{_title(k)}: {vv if vv is not None else '—'}")
        elif isinstance(v, list):
            for i in v:
                if isinstance(i, (dict, list)):
                    emit(i, level + 1)
                    doc.add_paragraph("")
                else:
                    doc.add_paragraph(str(i), style="List Bullet")
        else:
            doc.add_paragraph(str(v))

    for title, content in _sections(report):
        doc.add_heading(title, 1)
        emit(content)
    out = io.BytesIO()
    doc.save(out)
    return out.getvalue()


_FONT_CANDIDATES = [os.getenv("PDF_FONT_PATH", ""), "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
                    "/usr/share/fonts/dejavu/DejaVuSans.ttf", "/Library/Fonts/Arial Unicode.ttf",
                    "C:/Windows/Fonts/arial.ttf"]
_ARABIC = re.compile(r"[\u0600-\u06FF]")


def _pdf_font() -> str | None:
    """Register a TTF font with Arabic glyphs; returns its name or None (built-in Helvetica fallback)."""
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont

    if "DGSans" in pdfmetrics.getRegisteredFontNames():
        return "DGSans"
    for path in _FONT_CANDIDATES:
        if path and os.path.isfile(path):
            try:
                pdfmetrics.registerFont(TTFont("DGSans", path))
                bold_path = path.replace("DejaVuSans.ttf", "DejaVuSans-Bold.ttf")
                bold = "DGSans"
                if bold_path != path and os.path.isfile(bold_path):
                    pdfmetrics.registerFont(TTFont("DGSans-Bold", bold_path))
                    bold = "DGSans-Bold"
                pdfmetrics.registerFontFamily("DGSans", normal="DGSans", bold=bold, italic="DGSans", boldItalic=bold)
                return "DGSans"
            except Exception:  # pragma: no cover - unreadable font file
                continue
    return None


def _shape(text: str) -> str:
    """Arabic letters must be joined (reshaped) and laid out right-to-left before reportlab draws them."""
    if not _ARABIC.search(text):
        return text
    try:
        import arabic_reshaper
        from bidi.algorithm import get_display
    except ImportError:  # pragma: no cover
        return text
    return get_display(arabic_reshaper.reshape(text))


def to_pdf(report: Report) -> bytes:
    from xml.sax.saxutils import escape

    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

    styles = getSampleStyleSheet()
    font = _pdf_font()
    if font:
        for st in ("Title", "Heading2", "BodyText"):
            styles[st].fontName = font
    small = styles["BodyText"].clone("small", fontSize=8, leading=10)
    body = styles["BodyText"].clone("b", fontSize=9, leading=11)
    _esc = escape

    def escape(t: str) -> str:  # noqa: F811 - shape Arabic before XML-escaping
        return _esc(_shape(t))
    out = io.BytesIO()
    doc = SimpleDocTemplate(out, pagesize=A4, leftMargin=15 * mm, rightMargin=15 * mm, topMargin=15 * mm,
                            bottomMargin=15 * mm, title=report.title)
    story = [Paragraph(escape(report.title), styles["Title"]), Paragraph(escape(DISCLAIMER), small), Spacer(1, 6)]
    if not font and _ARABIC.search(json.dumps(report.content, ensure_ascii=False, default=str)):
        story.append(Paragraph("NOTE: Arabic text present but no Arabic-capable font found (set PDF_FONT_PATH). "
                               "Use the DOCX export for Arabic content.", small))
    rows = [[Paragraph(f"<b>{escape(k)}</b>", small),
             Paragraph("<br/>".join(escape(str(x)) for x in v) if isinstance(v, list) else escape(str(v)), small)]
            for k, v in header_info(report).items()]
    tbl = Table(rows, colWidths=[40 * mm, 140 * mm])
    tbl.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.25, colors.grey), ("VALIGN", (0, 0), (-1, -1), "TOP"),
                             ("BACKGROUND", (0, 0), (0, -1), colors.whitesmoke)]))
    story += [tbl, Spacer(1, 8)]

    def emit(v, depth=0):
        ind = "&nbsp;" * 4 * depth
        if isinstance(v, dict):
            for k, vv in v.items():
                if k in _SKIP_KEYS:
                    continue
                if isinstance(vv, (dict, list)):
                    story.append(Paragraph(f"{ind}<b>{escape(_title(k))}</b>", body))
                    emit(vv, depth + 1)
                else:
                    story.append(Paragraph(f"{ind}<b>{escape(_title(k))}:</b> {escape(str(vv) if vv is not None else '—')}", body))
        elif isinstance(v, list):
            for i in v:
                if isinstance(i, (dict, list)):
                    emit(i, depth + 1)
                    story.append(Spacer(1, 3))
                else:
                    story.append(Paragraph(f"{ind}• {escape(str(i))}", body))
        else:
            story.append(Paragraph(f"{ind}{escape(str(v))}", body))

    for title, content in _sections(report):
        story.append(Paragraph(escape(title), styles["Heading2"]))
        emit(content)
    doc.build(story)
    return out.getvalue()


EXPORTERS = {
    "pdf": (to_pdf, "application/pdf"),
    "docx": (to_docx, "application/vnd.openxmlformats-officedocument.wordprocessingml.document"),
    "xlsx": (to_xlsx, "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"),
    "csv": (to_csv, "text/csv"),
}
